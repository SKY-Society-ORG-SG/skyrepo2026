import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { IMAGE_WIDTHS } from './image-widths.mjs';

// Set by the GitHub Pages workflow: '' for a custom domain or user site,
// '/<repo-name>' for a project site served from <user>.github.io/<repo-name>.
const basePath = process.env.PAGES_BASE_PATH || '';

/** @type {import('next').NextConfig} */
const nextConfig = {
  output: 'export',
  trailingSlash: true,
  basePath,
  env: {
    NEXT_PUBLIC_BASE_PATH: basePath,
  },
  outputFileTracingRoot: path.dirname(fileURLToPath(import.meta.url)),
  images: {
    // Static hosting has no image optimizer, so images are resized at build
    // time by scripts/postbuild.mjs and served through this loader.
    loader: 'custom',
    loaderFile: './lib/imageLoader.ts',
    imageSizes: IMAGE_WIDTHS.slice(0, 1),
    deviceSizes: IMAGE_WIDTHS.slice(1),
  },
};

if (process.env.NODE_ENV === 'development') {
  // `next dev` and `next build` both write to .next by default. Running a
  // build while the dev server is up then deletes the dev server's compiled
  // chunks, and the next page it serves (e.g. after switching language) is
  // blank with "Cannot find module ./vendor-chunks/..." or "reading 'call'".
  nextConfig.distDir = '.next-dev';

  // The "/" redirect page is generated by scripts/postbuild.mjs, so it doesn't
  // exist under `npm run dev`; send "/" to English there instead of a 404.
  // (Static exports can't use redirects, so this is dev-only.)
  nextConfig.redirects = async () => [
    { source: '/', destination: '/en/', permanent: false },
  ];
}

export default nextConfig;
